//! The Moonraker Driver against the simulated-Klipper container (PRD §5.6):
//! real Klipper, on simulavr, behind real Moonraker. Run locally, never in
//! Actions:
//!
//! ```text
//! docker compose -f docker/simulators/compose.yaml up -d klipper
//! cargo test -p gantry-driver-moonraker --test simulated_klipper -- --ignored --test-threads 1
//! ```
//!
//! `GANTRY_MOONRAKER` is the simulator's address (`127.0.0.1:7125`),
//! `GANTRY_MOONRAKER_CAMERA` its test camera
//! (`http://127.0.0.1:8110/?action=stream`), and `GANTRY_MOONRAKER_CONTAINER`
//! its container (`gantry-klipper`), restarted to test reconnection.
//!
//! The simulated MCU is slow: Klipper finishes its queued moves before it
//! pauses or cancels, so those take tens of seconds here.
use std::sync::Arc;
use std::time::Duration;

use futures::StreamExt;
use gantry_core::{
    Capability, Command, Connection, DisconnectReason, DriverRegistry, FineControl, Fleet, Heater,
    JobOutcome, JobStart, JobState, MemoryJobLog, PrintUpload, PrinterConfig, PrinterState,
    PrinterView, Secrets,
};
use gantry_driver_moonraker::MoonrakerDriver;
use serde_json::{Value, json};

fn address() -> (String, u16) {
    let value = std::env::var("GANTRY_MOONRAKER").unwrap_or_else(|_| "127.0.0.1:7125".into());
    let (host, port) = value.rsplit_once(':').expect("host:port");
    (host.to_owned(), port.parse().expect("a port"))
}

fn base() -> String {
    let (host, port) = address();
    format!("http://{host}:{port}")
}

fn camera_url() -> String {
    std::env::var("GANTRY_MOONRAKER_CAMERA")
        .unwrap_or_else(|_| "http://127.0.0.1:8110/?action=stream".into())
}

fn config(id: &str, settings: Value) -> PrinterConfig {
    PrinterConfig {
        id: id.into(),
        name: format!("Klipper {id}"),
        settings: settings.as_object().unwrap().clone(),
        secrets: Secrets::default(),
    }
}

fn settings() -> Value {
    let (host, port) = address();
    json!({ "host": host, "port": port, "model": "Virtual Klipper" })
}

struct Harness {
    fleet: Fleet,
    log: Arc<MemoryJobLog>,
}

fn harness(settings: Value) -> Harness {
    let mut registry = DriverRegistry::new();
    registry.register(MoonrakerDriver);
    let log = Arc::new(MemoryJobLog::new());
    let fleet = Fleet::with_command_timeout(registry, log.clone(), Duration::from_secs(15));
    fleet
        .start("moonraker", config("k", settings), JobState::default())
        .unwrap();
    Harness { fleet, log }
}

impl Harness {
    async fn until(
        &self,
        secs: u64,
        what: &str,
        pred: impl Fn(&PrinterView) -> bool,
    ) -> PrinterView {
        match self
            .fleet
            .wait_for("k", Duration::from_secs(secs), &pred)
            .await
        {
            Ok(v) => (*v).clone(),
            Err(_) => panic!(
                "timed out waiting for {what}; the Printer is now {:#?}",
                self.fleet.view("k").unwrap().status
            ),
        }
    }

    async fn idle(&self) -> PrinterView {
        self.until(90, "an Idle Printer", |v| {
            v.status.connection.is_connected() && v.status.state == Some(PrinterState::Idle)
        })
        .await
    }
}

/// Plain G-code the simulator can print without homing (simulavr's
/// endstops never trigger): `layers` small squares.
fn gcode(layers: u32) -> String {
    let mut out = String::from(
        "; generated by Gantry's tests\n; printer_model = Virtual Klipper\n\
         SET_KINEMATIC_POSITION X=100 Y=100 Z=5\nG90\nM83\nG1 Z0.3 F600\n",
    );
    for layer in 0..layers {
        let z = 0.3 + 0.2 * f64::from(layer + 1);
        out.push_str(
            "G1 X50 Y50 F3000\nG1 X150 Y50 E1 F1200\nG1 X150 Y150 E1\nG1 X50 Y150 E1\nG1 X50 Y50 E1\n",
        );
        out.push_str(&format!("G1 Z{z:.2}\n"));
    }
    out
}

/// Starts a print through Moonraker itself, as Mainsail would: an External Job.
async fn print_outside_gantry(name: &str, gcode: String) {
    let form = reqwest::multipart::Form::new().text("print", "true").part(
        "file",
        reqwest::multipart::Part::bytes(gcode.into_bytes()).file_name(name.to_owned()),
    );
    let response = reqwest::Client::new()
        .post(format!("{}/server/files/upload", base()))
        .multipart(form)
        .send()
        .await
        .unwrap();
    assert!(
        response.status().is_success(),
        "{:?}",
        response.text().await
    );
}

/// Waits (up to 90 s) for Klipper to be ready, restarting its firmware if
/// an earlier run left it shut down.
async fn klipper_ready() {
    let client = reqwest::Client::new();
    for attempt in 0..45 {
        let state = client
            .get(format!("{}/printer/objects/query?webhooks", base()))
            .timeout(Duration::from_secs(3))
            .send()
            .await
            .ok();
        let state = match state {
            Some(r) => r.json::<Value>().await.ok(),
            None => None,
        };
        match state
            .as_ref()
            .and_then(|s| s["result"]["status"]["webhooks"]["state"].as_str())
        {
            Some("ready") => return,
            Some("shutdown" | "error") if attempt % 10 == 0 => {
                let _ = client
                    .post(format!("{}/printer/firmware_restart", base()))
                    .timeout(Duration::from_secs(5))
                    .send()
                    .await;
            }
            _ => {}
        }
        tokio::time::sleep(Duration::from_secs(2)).await;
    }
    panic!("the simulated Klipper never became ready");
}

#[tokio::test]
#[ignore = "needs the simulated-Klipper container"]
async fn status_reconnection_pause_resume_cancel_and_fine_controls() {
    klipper_ready().await;
    let h = harness(settings());
    let view = h.idle().await;
    assert_eq!(view.model.as_deref(), Some("Virtual Klipper"));
    let status = &view.status;
    assert!(status.temperatures.nozzle.is_some(), "{status:#?}");
    assert!(status.temperatures.bed.is_some(), "{status:#?}");
    for capability in [
        Capability::Pause,
        Capability::Resume,
        Capability::Cancel,
        Capability::NozzleTemperature,
        Capability::BedTemperature,
        Capability::Fans,
        Capability::Homing,
        Capability::Jogging,
    ] {
        assert!(
            status.has(capability),
            "{capability:?} in {:?}",
            status.capabilities
        );
    }

    // Fine controls: the bed's target, and the part fan.
    h.fleet
        .command(
            "k",
            Command::Fine(FineControl::SetTemperature {
                heater: Heater::Bed,
                target: 40.0,
            }),
        )
        .await
        .unwrap();
    h.until(20, "the bed's target", |v| {
        v.status.temperatures.bed.and_then(|b| b.target) == Some(40.0)
    })
    .await;
    h.fleet
        .command(
            "k",
            Command::Fine(FineControl::SetTemperature {
                heater: Heater::Bed,
                target: 0.0,
            }),
        )
        .await
        .unwrap();
    h.fleet
        .command(
            "k",
            Command::Fine(FineControl::SetFan {
                fan: "part".into(),
                percent: 50,
            }),
        )
        .await
        .unwrap();
    h.until(20, "the part fan at 50%", |v| {
        v.status.fans.first().is_some_and(|f| f.percent == 50)
    })
    .await;
    // Nothing to pause.
    assert!(h.fleet.command("k", Command::Pause).await.is_err());

    // A print started outside Gantry is an External Job, keyed by
    // Moonraker's job id.
    print_outside_gantry("gantry-external.gcode", gcode(60)).await;
    let view = h
        .until(60, "the print", |v| {
            v.status.state.is_some_and(PrinterState::has_job) && v.job.is_some()
        })
        .await;
    let active = view.status.job.unwrap();
    assert!(active.key.starts_with("moonraker-"), "{}", active.key);
    assert_eq!(active.print_file.as_deref(), Some("gantry-external.gcode"));
    assert!(view.job.unwrap().external);

    // Pause, resume and Cancel. Each waits for the slow simulator's queued moves.
    h.fleet.command("k", Command::Pause).await.unwrap();
    h.until(120, "Paused", |v| {
        v.status.state == Some(PrinterState::Paused)
    })
    .await;
    h.fleet.command("k", Command::Resume).await.unwrap();
    h.until(120, "printing again", |v| {
        v.status.state == Some(PrinterState::Printing)
    })
    .await;
    h.fleet.command("k", Command::Cancel).await.unwrap();
    let view = h
        .until(180, "Awaiting Clear after Cancel", |v| {
            v.status.state == Some(PrinterState::AwaitingClear)
        })
        .await;
    assert_eq!(
        view.awaiting_clear.unwrap().outcome,
        Some(JobOutcome::Cancelled)
    );
    let jobs = h.log.jobs();
    assert_eq!(jobs.len(), 1, "{jobs:?}");
    assert_eq!(jobs[0].driver_key, active.key);
    h.fleet.mark_clear("k", false).await.unwrap();

    // The print's G-code set the axes homed, so a jog moves the toolhead.
    let before = h
        .until(30, "a position", |v| v.status.position.is_some())
        .await
        .status
        .position
        .unwrap();
    let distance = if before.x > 150.0 { -10.0 } else { 10.0 };
    h.fleet
        .command(
            "k",
            Command::Fine(FineControl::Jog {
                axis: gantry_core::Axis::X,
                distance_mm: distance,
            }),
        )
        .await
        .unwrap();
    h.until(60, "the toolhead moved", |v| {
        v.status
            .position
            .is_some_and(|p| (p.x - (before.x + distance)).abs() < 0.5)
    })
    .await;

    // Reconnection: the container goes away and comes back.
    if let Ok(container) = std::env::var("GANTRY_MOONRAKER_CONTAINER") {
        let restarted = std::process::Command::new("docker")
            .args(["restart", &container])
            .status()
            .unwrap();
        assert!(restarted.success());
        h.until(60, "the Connection lost", |v| {
            matches!(v.status.connection, Connection::Disconnected { .. })
        })
        .await;
        klipper_ready().await;
        h.idle().await;
    }
    h.fleet.stop_all().await;
}

#[tokio::test]
#[ignore = "needs the simulated-Klipper container"]
async fn nothing_answering_is_unreachable() {
    let h = harness(json!({ "host": "127.0.0.1", "port": 9 }));
    let view = h
        .until(20, "unreachable", |v| {
            matches!(
                v.status.connection,
                Connection::Disconnected {
                    reason: DisconnectReason::Unreachable,
                    ..
                }
            )
        })
        .await;
    assert!(view.status.state.is_none());
}

#[tokio::test]
#[ignore = "needs the simulated-Klipper container"]
async fn upload_start_and_the_camera() {
    klipper_ready().await;
    let h = harness(json!({
        "host": address().0, "port": address().1, "model": "Virtual Klipper",
        "camera_url": camera_url(),
    }));
    let view = h.idle().await;
    assert!(view.status.has(Capability::UploadAndStart));
    assert!(view.status.has(Capability::Camera));

    // Gantry sends a Plate and starts it.
    let gcode = gcode(30);
    let job = h
        .fleet
        .start_job(
            "k",
            JobStart {
                print_file_id: 7,
                print_file: "gantry-upload.gcode".into(),
                plate: 1,
            },
            PrintUpload {
                file_name: "gantry-upload.gcode".into(),
                plate: None,
                data: gcode.into_bytes().into(),
                estimated_secs: None,
                layers: None,
            },
        )
        .await
        .unwrap();
    assert!(!job.external);
    let view = h
        .until(60, "the uploaded print", |v| {
            v.status.job.is_some() && v.job.as_ref().is_some_and(|j| !j.driver_key.is_empty())
        })
        .await;
    let recorded = view.job.unwrap();
    assert_eq!(recorded.id, job.id, "the same Job, now keyed");
    assert_eq!(
        view.status.job.unwrap().print_file.as_deref(),
        Some("gantry-upload.gcode")
    );

    // The camera gives JPEG frames, as the relay reads them.
    let camera = h.fleet.handle("k").unwrap().camera().expect("a camera");
    let frames: Vec<_> =
        tokio::time::timeout(Duration::from_secs(20), camera.open().take(2).collect())
            .await
            .expect("frames");
    for frame in frames {
        let frame = frame.unwrap();
        assert_eq!(&frame[..2], &[0xFF, 0xD8], "a JPEG");
    }

    h.fleet.command("k", Command::Cancel).await.unwrap();
    h.until(180, "Awaiting Clear", |v| {
        v.status.state == Some(PrinterState::AwaitingClear)
    })
    .await;
    h.fleet.stop_all().await;
}

#[tokio::test]
#[ignore = "needs the simulated-Klipper container"]
async fn the_camera_moonraker_lists_is_used_when_none_is_set() {
    klipper_ready().await;
    let client = reqwest::Client::new();
    let added = client
        .post(format!("{}/server/webcams/item", base()))
        .json(&json!({ "name": "gantry-test", "stream_url": camera_url(), "service": "mjpegstreamer" }))
        .send()
        .await
        .unwrap();
    assert!(added.status().is_success(), "{:?}", added.text().await);
    let h = harness(settings());
    let view = h.idle().await;
    assert!(
        view.status.has(Capability::Camera),
        "{:?}",
        view.status.capabilities
    );
    let camera = h.fleet.handle("k").unwrap().camera().unwrap();
    let frame = tokio::time::timeout(Duration::from_secs(20), camera.open().next())
        .await
        .unwrap()
        .unwrap()
        .unwrap();
    assert_eq!(&frame[..2], &[0xFF, 0xD8]);
    let _ = client
        .delete(format!("{}/server/webcams/item?name=gantry-test", base()))
        .send()
        .await;
    h.fleet.stop_all().await;
}
