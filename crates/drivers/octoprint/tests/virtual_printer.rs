//! The OctoPrint Driver end to end against OctoPrint's virtual printer in
//! Docker (PRD §5.6). Run locally, never in Actions:
//!
//! ```text
//! docker compose -f docker/simulators/compose.yaml up -d --build octoprint
//! cargo test -p gantry-driver-octoprint --test virtual_printer -- --ignored --test-threads 1
//! ```
//!
//! `GANTRY_OCTOPRINT` is its address (`127.0.0.1:5080`),
//! `GANTRY_OCTOPRINT_API_KEY` its test API key (the one in
//! `docker/simulators/octoprint/users.yaml`), and
//! `GANTRY_OCTOPRINT_CONTAINER` its container (`gantry-octoprint`),
//! restarted to test reconnection.
use std::sync::Arc;
use std::time::Duration;

use futures::StreamExt;
use gantry_core::{
    Capability, Command, Connection, DisconnectReason, DriverRegistry, FineControl, Fleet, Heater,
    JobOutcome, JobStart, JobState, MemoryJobLog, PrintUpload, PrinterConfig, PrinterState,
    PrinterView, Secrets,
};
use gantry_driver_octoprint::OctoPrintDriver;
use serde_json::{Value, json};
use tokio::io::{AsyncReadExt, AsyncWriteExt};

const TEST_KEY: &str = "GANTRYTESTKEY0123456789ABCDEFGHIJ";

fn address() -> (String, u16) {
    let value = std::env::var("GANTRY_OCTOPRINT").unwrap_or_else(|_| "127.0.0.1:5080".into());
    let (host, port) = value.rsplit_once(':').expect("host:port");
    (host.to_owned(), port.parse().expect("a port"))
}

fn base() -> String {
    let (host, port) = address();
    format!("http://{host}:{port}")
}

fn api_key() -> String {
    std::env::var("GANTRY_OCTOPRINT_API_KEY").unwrap_or_else(|_| TEST_KEY.into())
}

fn printer(settings: Value, key: &str) -> PrinterConfig {
    PrinterConfig {
        id: "o".into(),
        name: "OctoPrint".into(),
        settings: settings.as_object().unwrap().clone(),
        secrets: Secrets::new([("api_key".to_owned(), key.to_owned())].into()),
    }
}

fn settings() -> Value {
    let (host, port) = address();
    json!({ "host": host, "port": port, "model": "Virtual Printer" })
}

struct Harness {
    fleet: Fleet,
    log: Arc<MemoryJobLog>,
}

fn harness(config: PrinterConfig) -> Harness {
    let mut registry = DriverRegistry::new();
    registry.register(OctoPrintDriver);
    let log = Arc::new(MemoryJobLog::new());
    let fleet = Fleet::with_command_timeout(registry, log.clone(), Duration::from_secs(15));
    fleet
        .start("octoprint", config, JobState::default())
        .unwrap();
    Harness { fleet, log }
}

impl Harness {
    async fn until(
        &self,
        secs: u64,
        what: &str,
        pred: impl Fn(&PrinterView) -> bool,
    ) -> PrinterView {
        match self
            .fleet
            .wait_for("o", Duration::from_secs(secs), &pred)
            .await
        {
            Ok(v) => (*v).clone(),
            Err(_) => panic!(
                "timed out waiting for {what}; the Printer is now {:#?}",
                self.fleet.view("o").unwrap().status
            ),
        }
    }

    async fn idle(&self) -> PrinterView {
        self.until(120, "an Idle Printer", |v| {
            v.status.connection.is_connected() && v.status.state == Some(PrinterState::Idle)
        })
        .await
    }
}

/// G-code the virtual printer takes about a second a layer over.
fn gcode(layers: u32) -> String {
    let mut out = String::from("; generated by Gantry's tests\nG28\nG90\nM83\nG1 Z0.3 F600\n");
    for layer in 0..layers {
        let z = 0.3 + 0.2 * f64::from(layer + 1);
        out.push_str("G1 X50 Y50 F3000\nG1 X150 Y50 E1 F1200\nG1 X150 Y150 E1\nG1 X50 Y150 E1\nG1 X50 Y50 E1\n");
        out.push_str(&format!("G1 Z{z:.2}\n"));
    }
    out
}

fn client() -> reqwest::Client {
    let mut headers = reqwest::header::HeaderMap::new();
    headers.insert("X-Api-Key", api_key().parse().unwrap());
    reqwest::Client::builder()
        .default_headers(headers)
        .build()
        .unwrap()
}

/// Starts a print through OctoPrint itself: an External Job.
async fn print_outside_gantry(name: &str, gcode: String) {
    let form = reqwest::multipart::Form::new()
        .text("select", "true")
        .text("print", "true")
        .part(
            "file",
            reqwest::multipart::Part::bytes(gcode.into_bytes()).file_name(name.to_owned()),
        );
    let response = client()
        .post(format!("{}/api/files/local", base()))
        .multipart(form)
        .send()
        .await
        .unwrap();
    assert!(
        response.status().is_success(),
        "{:?}",
        response.text().await
    );
}

/// Makes sure nothing is printing, as an earlier failed run might leave it.
async fn nothing_printing() {
    let _ = client()
        .post(format!("{}/api/job", base()))
        .json(&json!({ "command": "cancel" }))
        .send()
        .await;
    for _ in 0..60 {
        let job: Value = client()
            .get(format!("{}/api/job", base()))
            .send()
            .await
            .unwrap()
            .json()
            .await
            .unwrap();
        if job["state"] == "Operational" {
            return;
        }
        tokio::time::sleep(Duration::from_secs(1)).await;
    }
    panic!("the virtual printer never became Operational");
}

#[tokio::test]
#[ignore = "needs OctoPrint's virtual printer in Docker"]
async fn status_reconnection_pause_resume_cancel_and_fine_controls() {
    nothing_printing().await;
    let h = harness(printer(settings(), &api_key()));
    let view = h.idle().await;
    assert_eq!(view.model.as_deref(), Some("Virtual Printer"));
    assert!(
        view.status.temperatures.nozzle.is_some(),
        "{:#?}",
        view.status
    );
    assert!(view.status.temperatures.bed.is_some());
    for capability in [
        Capability::Pause,
        Capability::Resume,
        Capability::Cancel,
        Capability::UploadAndStart,
        Capability::NozzleTemperature,
        Capability::BedTemperature,
        Capability::Homing,
        Capability::Jogging,
    ] {
        assert!(view.status.has(capability), "{capability:?}");
    }

    // Fine controls: targets the virtual printer heats to, homing, jogging.
    for (heater, target) in [(Heater::Bed, 50.0), (Heater::Nozzle, 180.0)] {
        h.fleet
            .command(
                "o",
                Command::Fine(FineControl::SetTemperature { heater, target }),
            )
            .await
            .unwrap();
    }
    h.until(30, "both targets", |v| {
        v.status.temperatures.bed.and_then(|t| t.target) == Some(50.0)
            && v.status.temperatures.nozzle.and_then(|t| t.target) == Some(180.0)
    })
    .await;
    for heater in [Heater::Bed, Heater::Nozzle] {
        h.fleet
            .command(
                "o",
                Command::Fine(FineControl::SetTemperature {
                    heater,
                    target: 0.0,
                }),
            )
            .await
            .unwrap();
    }
    h.fleet
        .command("o", Command::Fine(FineControl::Home))
        .await
        .unwrap();
    h.fleet
        .command(
            "o",
            Command::Fine(FineControl::Jog {
                axis: gantry_core::Axis::X,
                distance_mm: 10.0,
            }),
        )
        .await
        .unwrap();
    assert!(
        h.fleet.command("o", Command::Pause).await.is_err(),
        "nothing to pause"
    );

    // A print started outside Gantry is an External Job.
    print_outside_gantry("gantry-external.gcode", gcode(200)).await;
    let view = h
        .until(60, "the print", |v| {
            v.status.state.is_some_and(PrinterState::has_job) && v.job.is_some()
        })
        .await;
    let active = view.status.job.unwrap();
    assert_eq!(active.print_file.as_deref(), Some("gantry-external.gcode"));
    assert!(view.job.unwrap().external);

    h.until(60, "printing", |v| {
        v.status.state == Some(PrinterState::Printing)
    })
    .await;
    h.fleet.command("o", Command::Pause).await.unwrap();
    h.until(60, "Paused", |v| {
        v.status.state == Some(PrinterState::Paused)
    })
    .await;
    h.fleet.command("o", Command::Resume).await.unwrap();
    h.until(60, "printing again", |v| {
        v.status.state == Some(PrinterState::Printing)
    })
    .await;
    h.fleet.command("o", Command::Cancel).await.unwrap();
    let view = h
        .until(90, "Awaiting Clear after Cancel", |v| {
            v.status.state == Some(PrinterState::AwaitingClear)
        })
        .await;
    assert_eq!(
        view.awaiting_clear.unwrap().outcome,
        Some(JobOutcome::Cancelled)
    );
    let jobs = h.log.jobs();
    assert_eq!(jobs.len(), 1, "{jobs:?}");
    assert_eq!(jobs[0].driver_key, active.key);
    h.fleet.mark_clear("o", false).await.unwrap();

    if let Ok(container) = std::env::var("GANTRY_OCTOPRINT_CONTAINER") {
        let restarted = std::process::Command::new("docker")
            .args(["restart", &container])
            .status()
            .unwrap();
        assert!(restarted.success());
        h.until(90, "the Connection lost", |v| {
            matches!(v.status.connection, Connection::Disconnected { .. })
        })
        .await;
        h.idle().await;
    }
    h.fleet.stop_all().await;
}

#[tokio::test]
#[ignore = "needs OctoPrint's virtual printer in Docker"]
async fn a_wrong_api_key_is_refused_and_nothing_answering_is_unreachable() {
    let h = harness(printer(settings(), "not-the-key"));
    h.until(30, "authentication rejected", |v| {
        matches!(
            v.status.connection,
            Connection::Disconnected {
                reason: DisconnectReason::AuthenticationRejected,
                ..
            }
        )
    })
    .await;
    h.fleet.stop_all().await;
    let h = harness(printer(
        json!({ "host": "127.0.0.1", "port": 9 }),
        &api_key(),
    ));
    h.until(30, "unreachable", |v| {
        matches!(
            v.status.connection,
            Connection::Disconnected {
                reason: DisconnectReason::Unreachable,
                ..
            }
        )
    })
    .await;
    h.fleet.stop_all().await;
}

fn jpeg() -> Vec<u8> {
    vec![0xFF, 0xD8, 0xFF, 0xE0, 0x00, 0x10, 0xFF, 0xD9]
}

/// A local MJPEG streamer for OctoPrint to name as its webcam.
async fn streamer() -> String {
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let address = listener.local_addr().unwrap();
    tokio::spawn(async move {
        while let Ok((mut socket, _)) = listener.accept().await {
            tokio::spawn(async move {
                let mut request = [0u8; 1024];
                let _ = socket.read(&mut request).await;
                let _ = socket
                    .write_all(b"HTTP/1.1 200 OK\r\nContent-Type: multipart/x-mixed-replace;boundary=frame\r\n\r\n")
                    .await;
                loop {
                    let mut part = b"--frame\r\nContent-Type: image/jpeg\r\n\r\n".to_vec();
                    part.extend_from_slice(&jpeg());
                    part.extend_from_slice(b"\r\n");
                    if socket.write_all(&part).await.is_err() {
                        return;
                    }
                    tokio::time::sleep(Duration::from_millis(50)).await;
                }
            });
        }
    });
    format!("http://{address}/?action=stream")
}

#[tokio::test]
#[ignore = "needs OctoPrint's virtual printer in Docker"]
async fn upload_start_to_success_and_the_camera_octoprint_names() {
    nothing_printing().await;
    // OctoPrint's webcam is a local streamer.
    let camera = streamer().await;
    let saved = client()
        .post(format!("{}/api/settings", base()))
        .json(&json!({
            "webcam": { "webcamEnabled": true },
            "plugins": { "classicwebcam": { "stream": camera } },
        }))
        .send()
        .await
        .unwrap();
    assert!(saved.status().is_success(), "{:?}", saved.text().await);

    let h = harness(printer(settings(), &api_key()));
    let view = h.idle().await;
    assert!(
        view.status.has(Capability::Camera),
        "{:?}",
        view.status.capabilities
    );
    let source = h.fleet.handle("o").unwrap().camera().unwrap();
    let frames: Vec<_> =
        tokio::time::timeout(Duration::from_secs(20), source.open().take(2).collect())
            .await
            .unwrap();
    assert!(
        frames
            .iter()
            .all(|f| f.as_ref().is_ok_and(|f| f[..] == jpeg()[..]))
    );

    // Gantry sends a Plate and starts it; it prints to the end.
    let job = h
        .fleet
        .start_job(
            "o",
            JobStart {
                print_file_id: 3,
                print_file: "gantry-upload.gcode".into(),
                plate: 1,
            },
            PrintUpload {
                file_name: "gantry-upload.gcode".into(),
                plate: None,
                data: gcode(8).into_bytes().into(),
                estimated_secs: None,
                layers: None,
            },
        )
        .await
        .unwrap();
    let view = h
        .until(60, "the uploaded print", |v| {
            v.status.job.is_some() && v.job.as_ref().is_some_and(|j| !j.driver_key.is_empty())
        })
        .await;
    assert_eq!(view.job.unwrap().id, job.id, "the same Job, now keyed");
    let view = h
        .until(180, "the print to succeed", |v| {
            v.status.state == Some(PrinterState::AwaitingClear)
        })
        .await;
    let ended = view.awaiting_clear.unwrap();
    assert_eq!(ended.id, job.id);
    assert_eq!(
        ended.outcome,
        Some(JobOutcome::Succeeded),
        "from OctoPrint's PrintDone"
    );
    let _ = client()
        .post(format!("{}/api/settings", base()))
        .json(&json!({ "webcam": { "webcamEnabled": false } }))
        .send()
        .await;
    h.fleet.stop_all().await;
}
